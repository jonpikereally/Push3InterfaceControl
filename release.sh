#!/bin/zsh
# Build a release: universal (Apple Silicon + Intel) app with an installer,
# written to updates/PushBar.zip + updates/latest.json. Committing and
# pushing updates/ ships it: every installed copy's "Check for Updates" reads
# latest.json from this repo on GitHub.
#
# Usually you don't run this yourself: bump VERSION, write the notes in
# RELEASE_NOTES.txt, and merge to main. .github/workflows/release.yml then runs
# this on a Mac and commits updates/. To ship by hand instead:
#   UPDATE_NOTES="What changed" ./release.sh
# (without UPDATE_NOTES the notes come from RELEASE_NOTES.txt)
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'PB-[0-9]{3}' Sources/PushBar/*.swift release.sh | sort -u | while read -r c; do
  grep -q "^| $c |" ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/jonpikereally/Push3InterfaceControl/main/updates/latest.json}"
cat > Sources/PushBar/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/pushbar-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/PushBar-arm64" Sources/PushBar/*.swift
echo "Building x86_64…"
swiftc -O -target x86_64-apple-macos13 -module-cache-path "$CACHE-x86" \
  -o "$CACHE/PushBar-x86_64" Sources/PushBar/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/PushBar/PushBar.app"
mkdir -p "$APP/Contents/MacOS"
lipo -create -output "$APP/Contents/MacOS/PushBar" \
  "$CACHE/PushBar-arm64" "$CACHE/PushBar-x86_64"
cp Resources/Info.plist "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

cat > "$DIST/PushBar/Install PushBar.command" <<'INSTALL'
#!/bin/bash
# PushBar installer — copies the app to ~/Applications and launches it.
cd "$(dirname "$0")"
fail() {
  echo
  echo "Error $1: $2"
  echo "Look up this code on the PushBar error list:"
  echo "  https://github.com/jonpikereally/Push3InterfaceControl/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing PushBar…"
mkdir -p ~/Applications || fail PB-601 "Couldn't create ~/Applications."
rm -rf ~/Applications/PushBar.app
ditto --norsrc PushBar.app ~/Applications/PushBar.app \
  || fail PB-601 "Couldn't copy PushBar into ~/Applications."
# Clear the download quarantine and re-sign locally so macOS trusts it on this Mac.
xattr -dr com.apple.quarantine ~/Applications/PushBar.app 2>/dev/null
codesign --force --sign - ~/Applications/PushBar.app 2>/dev/null \
  || fail PB-602 "Couldn't sign PushBar for this Mac."
open ~/Applications/PushBar.app \
  || fail PB-603 "PushBar was installed but couldn't be opened. Open it from ~/Applications yourself."
echo
echo "Done! Look for the pad-grid icon in your menu bar."
INSTALL
chmod +x "$DIST/PushBar/Install PushBar.command"

cat > "$DIST/PushBar/README.txt" <<README
PushBar v$VERSION — menu bar control for Ableton Push 3's audio interface
on macOS (13+), without Ableton Live running
https://github.com/jonpikereally/Push3InterfaceControl

INSTALL
Double-click "Install PushBar.command".
If macOS blocks it: right-click it, choose Open, then Open again.

USE
• Plug Push 3 into the Mac over USB-C. If you've just quit Live and Push
  has gone dark, unplug its USB cable and plug it back in.
• Click the menu bar icon: Master, Main Out and Headphones levels with
  mute, Input 1/2 gain (0 to +20 dB) with mute, and a link button to move
  left and right separately
• Mac Output / Mac Input make Push the Mac's sound output or input
• Sample Rate: 44.1 / 48 / 88.2 / 96 kHz
• The Mac's own volume keys move Master while Push is the sound output

PRIVACY
PushBar only talks to Push through macOS's audio system. No accounts, no
analytics. The only thing it fetches from the internet is a small version
file from the GitHub repo above, to see whether an update exists.
README

mkdir -p updates
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent PushBar "$OLDPWD/updates/PushBar.zip.tmp")
mv -f updates/PushBar.zip.tmp updates/PushBar.zip
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "PushBar.zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > updates/latest.json.tmp
mv -f updates/latest.json.tmp updates/latest.json

./build.sh >/dev/null
echo "Release v$VERSION written to updates/. Ship it with:"
echo "  git add -A && git commit -m \"Release v$VERSION\" && git push"
